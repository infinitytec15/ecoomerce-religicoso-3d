import { z } from 'zod';
import { assertKitPieces } from './shared';
import {
  inventoryProductSchema,
  workspaceSchema,
  publicSettingsSchema,
  editionSchema,
  couponSchema,
  permissionSchema,
  addressSchema,
} from '@maos-em-oracao/contracts';
const id = z.string().min(1).max(100),
  text = z.string().max(2000),
  date = z.string().refine((v) => Number.isFinite(Date.parse(v)), 'Informe uma data válida.'),
  priority = z.enum(['Normal', 'Alta']),
  status = z.enum([
    'Aguardando pagamento',
    'Aguardando grupo',
    'Confirmado',
    'Em produção',
    'Em acabamento',
    'Pronto para envio',
    'Enviado',
    'Entregue',
    'Cancelado',
  ]);
const customer = addressSchema.partial().extend({
  id: id.optional(),
  name: z.string().trim().min(3).max(120),
  email: z.email(),
  notes: text.optional(),
  status: z.enum(['Ativo', 'Inativo']).optional(),
  created: date.optional(),
});
const campaign = z.object({
  id,
  subject: z.string().min(3).max(160),
  message: z.string().min(10).max(5000),
  date,
  recipients: z.number().int().nonnegative(),
  status: z.string().max(40),
  previewText: z.string().max(5000).optional(),
  scheduledAt: date.optional(),
  audience: z.enum(['Inscritos em oração', 'Assinantes do clube']).optional(),
});
export const commandSchema = z.discriminatedUnion('type', [
  z.object({
    type: z.literal('product.save'),
    product: z.preprocess(assertKitPieces, inventoryProductSchema),
  }),
  z.object({ type: z.literal('product.archive'), id }),
  z.object({
    type: z.literal('stock.adjust'),
    productId: id,
    delta: z.number().int(),
    reason: z.string().trim().min(5).max(500),
  }),
  z.object({ type: z.literal('customer.save'), customer }),
  z.object({ type: z.literal('customer.archive'), id }),
  z.object({ type: z.literal('customer.delete'), id }),
  z.object({ type: z.literal('order.delete'), id }),
  z.object({ type: z.literal('order.update'), id, status, priority, due: date, notes: text }),
  z.object({
    type: z.literal('order.create'),
    customerId: id,
    productId: id,
    quantity: z.number().int().min(1).max(50),
    shippingCents: z.number().int().nonnegative(),
    paid: z.boolean(),
    due: date,
  }),
  z.object({
    type: z.literal('orders.batch'),
    ids: z.array(id).min(1).max(100),
    action: z.enum(['priority', 'cancel', 'production']),
  }),
  z.object({
    type: z.literal('production.create'),
    orderId: id,
    printer: z.string().max(100),
    hours: z.number().min(0.1).max(168),
    assignee: z.string().max(100),
  }),
  z.object({ type: z.literal('production.advance'), id }),
  z.object({
    type: z.literal('production.update'),
    id,
    printer: z.string().max(100),
    hours: z.number().min(0.1).max(168),
    assignee: z.string().max(100),
    due: date,
    priority,
    notes: text,
    material: z.string().max(100),
    grams: z.number().nonnegative().max(100000),
  }),
  z.object({
    type: z.literal('printer.update'),
    id,
    status: z.enum(['Disponível', 'Imprimindo', 'Manutenção']),
  }),
  z.object({
    type: z.literal('shipping.label'),
    id,
    action: z.enum(['prepare', 'generate', 'cancel']),
  }),
  z.object({
    type: z.literal('shipping.dispatch'),
    id,
    tracking: z.string().min(5).max(100),
    carrier: z.string().min(2).max(100),
  }),
  z.object({ type: z.literal('shipping.deliver'), id }),
  z.object({ type: z.literal('charge.pay'), id }),
  z.object({ type: z.literal('charge.refund'), id, reason: z.string().min(5).max(500) }),
  z.object({
    type: z.literal('expense.create'),
    expense: z.object({
      name: z.string().min(3).max(160),
      amountCents: z.number().int().positive().max(100000000),
      category: z.string().min(1).max(80),
      date,
      status: z.enum(['Previsto', 'Pago']),
    }),
  }),
  z.object({ type: z.literal('expense.pay'), id }),
  z.object({
    type: z.literal('subscription.renew'),
    id,
    result: z.enum(['Pago', 'Pendente', 'Recusado']),
  }),
  z.object({
    type: z.literal('subscription.state'),
    id,
    status: z.enum(['Ativa', 'Pausada', 'Pagamento pendente', 'Cancelada']),
  }),
  z.object({ type: z.literal('edition.save'), edition: editionSchema }),
  z.object({ type: z.literal('edition.activate'), id }),
  z.object({ type: z.literal('coupon.save'), coupon: couponSchema }),
  z.object({ type: z.literal('coupon.archive'), id }),
  z.object({
    type: z.literal('ticket.reply'),
    id,
    message: z.string().min(1).max(5000),
    status: z.enum(['Aberto', 'Em atendimento', 'Resolvido']),
    assignee: z.string().max(100),
    internal: z.boolean().optional(),
    priority: priority.optional(),
  }),
  z.object({ type: z.literal('prayer.moderate'), id }),
  z.object({
    type: z.literal('review.moderate'),
    id,
    status: z.enum(['Publicado', 'Em análise', 'Oculto']),
    reply: z.string().max(1000),
  }),
  z.object({
    type: z.literal('prayer.review'),
    id,
    status: z.enum(['Publicado', 'Em análise', 'Oculto']),
    note: text,
  }),
  z.object({
    type: z.literal('campaign.create'),
    campaign: campaign.pick({ subject: true, message: true, date: true }),
  }),
  z.object({ type: z.literal('campaign.save'), campaign }),
  z.object({
    type: z.literal('campaign.action'),
    id,
    action: z.enum(['schedule', 'cancel', 'draft']),
  }),
  z.object({
    type: z.literal('team.save'),
    member: z.object({
      id,
      name: z.string().min(3).max(120),
      email: z.email(),
      role: z.string().max(40),
      status: z.enum(['Ativo', 'Inativo']),
      permissions: z.array(permissionSchema).optional(),
      lastSeen: z.string().optional(),
    }),
  }),
  z.object({
    type: z.literal('invite.create'),
    name: z.string().min(3).max(120),
    email: z.email(),
    role: z.enum(['admin', 'support', 'production', 'finance']),
    permissions: z.array(permissionSchema),
  }),
  z.object({ type: z.enum(['invite.revoke', 'invite.resend']), id }),
  z.object({ type: z.literal('workspace.save'), settings: workspaceSchema }),
  z.object({ type: z.literal('settings.save'), settings: publicSettingsSchema }),
]);
export type Command = z.infer<typeof commandSchema>;
