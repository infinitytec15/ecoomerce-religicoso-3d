import { z } from 'zod';
import { adminReviewSchema, httpsUrlSchema, myReviewSchema } from '@maos-em-oracao/contracts';
import {
  workspaceSchema,
  invitationSchema,
  editionSchema,
  couponSchema,
  stockMovementSchema,
  productMediaSchema,
} from '@/lib/domain/admin-schemas';
import { addressSchema, inventoryProductSchema, publicSettingsSchema } from '@/lib/domain/schemas';
const id = z.string().min(1),
  cents = z.number().int().nonnegative(),
  text = z.string();
export const sessionSchema = z.object({
  guest: z.boolean().optional(),
  id,
  name: text,
  email: z.email(),
  role: z.enum(['customer', 'admin', 'support', 'production', 'finance']),
  permissions: z.array(
    z.enum([
      'orders',
      'subscriptions',
      'production',
      'shipping',
      'catalog',
      'customers',
      'finance',
      'support',
      'community',
      'marketing',
      'reports',
      'team',
      'settings',
    ]),
  ),
  owner: z.boolean().optional(),
  demo: z.boolean(),
});
const addressResponseSchema = addressSchema.extend({
  phone: text,
  cep: text,
  street: text,
  number: text,
  district: text,
  city: text,
  state: text,
  email: z.union([z.email(), z.literal('')]),
});
export const customerSchema = addressResponseSchema.extend({
  id,
  status: z.enum(['Ativo', 'Inativo']),
  created: text,
  notes: text,
});
export const cartItemSchema = z.object({
  key: text,
  productId: id,
  name: text,
  image: text,
  imageIndex: z.number().int(),
  color: text,
  size: text,
  sizeIndex: z.number().int(),
  unitCents: cents,
  quantity: z.number().int().positive(),
  dedication: text,
  itemId: id.optional(),
});
export const orderSchema = z.object({
  id,
  number: text,
  customerId: id,
  subscriptionId: text.optional(),
  type: z.enum(['Loja', 'Clube']),
  edition: text.optional(),
  items: z.array(cartItemSchema),
  totalCents: cents,
  subtotalCents: cents,
  discountCents: cents,
  shippingCents: cents,
  status: z.enum([
    'Aguardando pagamento',
    'Confirmado',
    'Em produção',
    'Em acabamento',
    'Pronto para envio',
    'Enviado',
    'Entregue',
    'Cancelado',
  ]),
  created: text,
  due: text,
  address: addressResponseSchema,
  chargeId: id,
  tracking: text,
  carrier: text,
  priority: z.enum(['Normal', 'Alta']),
  notes: text,
  sourceOrderId: text.optional(),
  shippingServiceId: text.optional(),
  shippingQuoteId: text.optional(),
  labelStatus: z.enum(['Não solicitada', 'Preparada', 'Gerada', 'Cancelada']).optional(),
  labelUrl: z.url().optional(),
});
export const subscriptionResponseSchema = z.object({
  id,
  customerId: id,
  profile: z.enum(['Católica', 'Evangélica', 'Cristã']),
  finish: text,
  priceCents: cents,
  status: z.enum(['Ativa', 'Pausada', 'Pagamento pendente', 'Cancelada']),
  payment: z.enum(['card', 'pix']),
  created: text,
  nextRenewal: text,
  nextShipment: text,
  address: addressSchema,
  history: z.array(z.object({ date: text, label: text })),
});
export const chargeSchema = z.object({
  id,
  customerId: id,
  subscriptionId: text.optional(),
  orderId: id,
  amountCents: cents,
  method: z.enum(['card', 'pix', 'split']),
  status: z.enum(['Pago', 'Pendente', 'Recusado', 'Cancelada', 'Estornado']),
  due: text,
  paidAt: text.optional(),
  description: text,
  cycle: text,
  pixCents: cents,
  cardCents: cents,
  installments: z.number().int(),
  refundReason: text.optional(),
});
export const ticketSchema = z.object({
  id,
  customerId: id,
  subject: text,
  category: text,
  status: z.enum(['Aberto', 'Em atendimento', 'Resolvido']),
  priority: z.enum(['Normal', 'Alta']),
  assignee: text,
  created: text,
  messages: z.array(
    z.object({
      by: z.enum(['cliente', 'equipe']),
      text,
      date: text,
      internal: z.boolean().optional(),
      attachments: z.array(productMediaSchema).optional(),
    }),
  ),
});
export const prayerResponseSchema = z.object({
  id,
  name: text,
  title: text,
  message: text,
  category: text,
  anonymous: z.boolean(),
  example: z.boolean(),
  hidden: z.boolean(),
  created: text,
  reactions: z.number().int().nonnegative(),
  owned: z.boolean(),
  prayed: z.boolean(),
  moderation: z.enum(['Publicado', 'Em análise', 'Oculto']).optional(),
  reports: z.array(z.object({ reason: text, date: text })).optional(),
  moderationNote: text.optional(),
});
export const accountSchema = z.object({
  customer: customerSchema,
  orders: z.array(orderSchema),
  subscriptions: z.array(subscriptionResponseSchema),
  charges: z.array(chargeSchema),
  tickets: z.array(ticketSchema),
  reviews: z.array(myReviewSchema),
});
export const operationsSchema = z.object({
  version: z.literal(2),
  workspace: workspaceSchema.extend({
    originCep: text,
    originStreet: text,
    originNumber: text,
    originDistrict: text,
    originCity: text,
    originState: text,
  }),
  invitations: z.array(invitationSchema),
  editions: z.array(editionSchema),
  coupons: z.array(couponSchema),
  stockMovements: z.array(stockMovementSchema),
  reviews: z.array(adminReviewSchema),
  products: z.array(inventoryProductSchema),
  clients: z.array(customerSchema),
  orders: z.array(orderSchema),
  subscriptions: z.array(subscriptionResponseSchema),
  charges: z.array(chargeSchema),
  tickets: z.array(ticketSchema),
  jobs: z.array(
    z.object({
      id,
      orderId: id,
      stage: z.enum(['Fila', 'Impressão', 'Acabamento', 'Conferência', 'Pronto']),
      printer: text,
      hours: z.number(),
      assignee: text,
      priority: z.enum(['Normal', 'Alta']),
      due: text,
      notes: text.optional(),
      material: text.optional(),
      grams: z.number().nonnegative().optional(),
      startedAt: text.optional(),
      completedAt: text.optional(),
    }),
  ),
  printers: z.array(
    z.object({
      id,
      name: text,
      status: z.enum(['Disponível', 'Imprimindo', 'Manutenção']),
      capacity: z.number(),
    }),
  ),
  expenses: z.array(
    z.object({
      id,
      name: text,
      amountCents: cents,
      category: text,
      date: text,
      status: z.enum(['Previsto', 'Pago']),
    }),
  ),
  team: z.array(
    z.object({
      id,
      name: text,
      email: text,
      role: text,
      status: z.enum(['Ativo', 'Inativo']),
      permissions: sessionSchema.shape.permissions.optional(),
      lastSeen: text.optional(),
    }),
  ),
  settings: publicSettingsSchema,
  campaigns: z.array(
    z.object({
      id,
      subject: text,
      message: text,
      date: text,
      recipients: z.number(),
      status: text,
      previewText: text.optional(),
      scheduledAt: text.optional(),
      audience: z.enum(['Inscritos em oração', 'Assinantes do clube']).optional(),
    }),
  ),
  audit: z.array(z.object({ id, date: text, actor: text, action: text, entity: text })),
  prayers: z.array(prayerResponseSchema),
  newsletter: z.object({ name: text, email: text, subscribed: z.boolean() }).nullable(),
  processed: z.record(text, z.object({ orderId: id, subscriptionId: text.optional() })),
});
export const checkoutResultSchema = z.object({
  orderId: id,
  subscriptionId: text.optional(),
  paymentAction: z.discriminatedUnion('type', [
    z.object({
      type: z.literal('challenge'),
      paymentId: z.string().min(1),
      externalResourceUrl: httpsUrlSchema,
      creq: z.string().min(1).max(16000),
    }),
    z.object({ type: z.literal('none') }),
    z.object({
      type: z.literal('redirect'),
      url: httpsUrlSchema,
    }),
    z.object({ type: z.literal('pix'), qrCode: text, copyPaste: text, expiresAt: text }),
  ]),
});
export const shippingResponseSchema = z.array(
  z.object({
    id: text,
    label: text,
    cents,
    estimate: text,
    quoteId: text.optional(),
    serviceId: text.optional(),
    carrier: text.optional(),
    expiresAt: text.optional(),
  }),
);
